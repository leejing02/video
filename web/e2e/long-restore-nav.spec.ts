// Long-video list state restore (sessionStorage `long-list-return`, browser-history returns
// only), list back arrow, and bottom-bar highlighting by where a video was opened from.
import { expect, test, type Page } from '@playwright/test'
import {
  expectRestoredList, frames, header, homeCards, listCalls, nav, openVisibleVideo, scrollListTo,
  scrollTop, setupLong, tiles,
} from './fixtures/long-video'

const backButton = (page: Page) => page.getByRole('button', { name: '返回', exact: true })
const savedReturn = (page: Page) => page.evaluate(() => JSON.parse(sessionStorage.getItem('long-list-return') || 'null'))

test.describe('从详情返回列表：恢复状态', () => {
  test('首页进入影视剧、加载两页、滚动、进详情，点页面返回 → 恢复数据和滚动位置，不重新请求', async ({ page }) => {
    const h = await setupLong(page)
    await page.goto('/long')
    await homeCards(page).filter({ hasText: '影视剧' }).click()
    await expect(tiles(page)).toHaveCount(30)
    await page.getByRole('button', { name: '加载更多' }).click()
    await expect(tiles(page)).toHaveCount(60)
    await scrollListTo(page, 2400)
    await openVisibleVideo(page)
    await expect(nav(page, '分类')).toHaveAttribute('aria-current', 'page')
    const from = h.calls.length
    await backButton(page).click()
    await expectRestoredList(page, { categoryId: 1, count: 60, top: 2400, firstTitle: /影视剧视频 1001/ })
    await expect(page.getByRole('button', { name: '加载更多' })).toHaveCount(0)
    await frames(page, 5)
    expect(listCalls(h, from), 'no list or category request on restore').toEqual([])
  })

  test('首页进入教育、滚动、进详情，浏览器返回 → 恢复', async ({ page }) => {
    const h = await setupLong(page)
    await page.goto('/long')
    await homeCards(page).filter({ hasText: '教育' }).click()
    await expect(tiles(page).first()).toContainText('教育视频 3001')
    await scrollListTo(page, 1500)
    await openVisibleVideo(page)
    const from = h.calls.length
    await page.goBack()
    await expectRestoredList(page, { categoryId: 3, count: 30, top: 1500, firstTitle: /教育视频 3001/ })
    expect(listCalls(h, from)).toEqual([])
  })

  test('直接打开列表链接，滚动、进详情、返回 → 同样恢复', async ({ page }) => {
    const h = await setupLong(page)
    await page.goto('/long/category/3')
    await expect(tiles(page)).toHaveCount(30)
    await scrollListTo(page, 900)
    await openVisibleVideo(page)
    const from = h.calls.length
    await backButton(page).click()
    await expectRestoredList(page, { categoryId: 3, count: 30, top: 900, firstTitle: /教育视频 3001/ })
    expect(listCalls(h, from)).toEqual([])
  })

  test('连续打开视频 A 返回、再滚动打开视频 B 返回：两次都恢复，没有旧缓存污染', async ({ page }) => {
    const h = await setupLong(page)
    await page.goto('/long/category/1')
    await expect(tiles(page)).toHaveCount(30)
    await scrollListTo(page, 1500)
    const a = await openVisibleVideo(page)
    expect((await savedReturn(page)).videoId).toBe(a)
    let from = h.calls.length
    await backButton(page).click()
    await expectRestoredList(page, { categoryId: 1, count: 30, top: 1500, firstTitle: /影视剧视频 1001/ })
    expect(listCalls(h, from)).toEqual([])
    await scrollListTo(page, 2100)
    const b = await openVisibleVideo(page)
    expect(b).not.toBe(a)
    expect(await savedReturn(page)).toMatchObject({ videoId: b, top: 2100 })
    from = h.calls.length
    await page.goBack()
    await expectRestoredList(page, { categoryId: 1, count: 30, top: 2100, firstTitle: /影视剧视频 1001/ })
    await frames(page, 5)
    expect(await scrollTop(page)).toBe(2100)
    expect(listCalls(h, from)).toEqual([])
  })

  test('恢复之后从首页进入另一个分类：从顶部开始，不沿用旧位置', async ({ page }) => {
    await setupLong(page)
    await page.goto('/long')
    await homeCards(page).filter({ hasText: '影视剧' }).click()
    await expect(tiles(page)).toHaveCount(30)
    await scrollListTo(page, 1500)
    await openVisibleVideo(page)
    await page.goBack()
    await expectRestoredList(page, { categoryId: 1, count: 30, top: 1500, firstTitle: /影视剧视频 1001/ })
    await header(page).getByRole('button', { name: '返回', exact: true }).click()
    await expect(page).toHaveURL(/\/long$/)
    await homeCards(page).filter({ hasText: '教育' }).click()
    await expect(tiles(page).first()).toContainText('教育视频 3001')
    await expect.poll(() => scrollTop(page)).toBe(0)
  })
})

test.describe('不应恢复的情况：安全回到正常加载', () => {
  test('恢复后刷新列表、重新打开列表 URL：不恢复，重新请求', async ({ page }) => {
    const h = await setupLong(page)
    await page.goto('/long/category/3')
    await expect(tiles(page)).toHaveCount(30)
    await scrollListTo(page, 1500)
    await openVisibleVideo(page)
    await page.goBack()
    await expectRestoredList(page, { categoryId: 3, count: 30, top: 1500, firstTitle: /教育视频 3001/ })
    await page.reload()
    await expect(tiles(page).first()).toContainText('教育视频 3001')
    await expect.poll(() => scrollTop(page)).toBe(0)
    const from = h.calls.length
    await page.goto('/long/category/3')
    await expect(tiles(page).first()).toContainText('教育视频 3001')
    expect(await scrollTop(page)).toBe(0)
    expect(listCalls(h, from).some(c => c.startsWith('/api/videos?'))).toBe(true)
  })

  for (const [label, corrupt] of [
    ['数据损坏', (p: Page) => p.evaluate(() => sessionStorage.setItem('long-list-return', '{broken'))],
    ['已过期（31 分钟前）', (p: Page) => p.evaluate(() => {
      const saved = JSON.parse(sessionStorage.getItem('long-list-return')!)
      sessionStorage.setItem('long-list-return', JSON.stringify({ ...saved, savedAt: Date.now() - 31 * 60 * 1000 }))
    })],
  ] as const) {
    test(`缓存${label}：返回时正常加载，不报错`, async ({ page }) => {
      const h = await setupLong(page)
      await page.goto('/long/category/3')
      await expect(tiles(page)).toHaveCount(30)
      await scrollListTo(page, 1500)
      await openVisibleVideo(page)
      await corrupt(page)
      const from = h.calls.length
      await page.goBack()
      await expect(page).toHaveURL(/\/long\/category\/3$/)
      await expect(tiles(page).first()).toContainText('教育视频 3001')
      expect(await scrollTop(page)).toBe(0)
      expect(listCalls(h, from).some(c => c.startsWith('/api/videos?'))).toBe(true)
      expect(h.pageErrors).toEqual([])
    })
  }

  test('sessionStorage 写入失败（配额）：照常进入详情，返回时正常加载', async ({ page }) => {
    const h = await setupLong(page, { blockReturnKey: true })
    await page.goto('/long/category/1')
    await expect(tiles(page)).toHaveCount(30)
    await scrollListTo(page, 1500)
    await openVisibleVideo(page)
    await page.goBack()
    await expect(page).toHaveURL(/\/long\/category\/1$/)
    await expect(tiles(page)).toHaveCount(30)
    expect(await scrollTop(page)).toBe(0)
    expect(h.pageErrors).toEqual([])
  })
})

test.describe('列表返回箭头', () => {
  test('遵循浏览器历史；直接打开列表时回到 /long', async ({ page }) => {
    await setupLong(page)
    await page.goto('/long')
    await homeCards(page).filter({ hasText: '教育' }).click()
    await expect(page).toHaveURL(/\/long\/category\/3$/)
    await header(page).getByRole('button', { name: '返回', exact: true }).click()
    await expect(page).toHaveURL(/\/long$/)
    await expect(homeCards(page)).toHaveCount(3)
    await page.goForward()
    await expect(page).toHaveURL(/\/long\/category\/3$/)
    await openVisibleVideo(page)
    await backButton(page).click()
    await expect(page).toHaveURL(/\/long\/category\/3$/)
    await header(page).getByRole('button', { name: '返回', exact: true }).click()
    await expect(page).toHaveURL(/\/long$/)
    await page.goto('/long/category/1')
    await expect(tiles(page)).toHaveCount(30)
    await header(page).getByRole('button', { name: '返回', exact: true }).click()
    await expect(page).toHaveURL(/\/long$/)
    await expect(homeCards(page)).toHaveCount(3)
  })
})

test.describe('底部导航', () => {
  test('顺序为 分类 | 推荐 | ＋ | 群聊 | 我；分类 → 推荐 → 分类 高亮与页面一致', async ({ page }) => {
    await setupLong(page)
    await page.goto('/long')
    await expect(page.locator('nav.bottom-nav button.tab-btn')).toHaveCount(5)
    const labels = await page.locator('nav.bottom-nav button.tab-btn').evaluateAll(buttons => buttons.map(b => b.getAttribute('aria-label')))
    expect(labels).toEqual(['分类', '推荐', '发布视频', '群聊', '我'])
    await expect(nav(page, '分类')).toHaveAttribute('aria-current', 'page')
    await nav(page, '推荐').click()
    await expect(page).toHaveURL(/\/short$/)
    await expect(nav(page, '推荐')).toHaveAttribute('aria-current', 'page')
    await nav(page, '分类').click()
    await expect(page).toHaveURL(/\/long$/)
    await expect(nav(page, '分类')).toHaveAttribute('aria-current', 'page')
    await expect(homeCards(page)).toHaveCount(3)
    await expect(page.locator('nav.bottom-nav [aria-current="page"]')).toHaveCount(1)
  })

  test('从「我的视频」进入详情高亮「我」；更多推荐、浏览器返回/前进后仍是「我」', async ({ page }) => {
    await setupLong(page)
    await page.goto('/long')
    await nav(page, '我').click()
    await expect(page).toHaveURL(/\/me$/)
    await page.getByRole('button', { name: '播放：我的视频 7001' }).click()
    await expect(page).toHaveURL(/\/video\/7001$/)
    await expect(nav(page, '我')).toHaveAttribute('aria-current', 'page')
    await expect(page.locator('nav.bottom-nav [aria-current="page"]')).toHaveCount(1)
    await page.locator('.more-card').first().click()
    await expect(page).not.toHaveURL(/\/video\/7001$/)
    await expect(nav(page, '我')).toHaveAttribute('aria-current', 'page')
    await page.goBack()
    await expect(page).toHaveURL(/\/video\/7001$/)
    await expect(nav(page, '我')).toHaveAttribute('aria-current', 'page')
    await page.goBack()
    await expect(page).toHaveURL(/\/me$/)
    await expect(nav(page, '我')).toHaveAttribute('aria-current', 'page')
    await page.goForward()
    await expect(page).toHaveURL(/\/video\/7001$/)
    await expect(nav(page, '我')).toHaveAttribute('aria-current', 'page')
  })

  test('从分类进入详情高亮「分类」；直接打开详情默认高亮「分类」', async ({ page }) => {
    await setupLong(page)
    await page.goto('/long/category/1')
    await expect(tiles(page)).toHaveCount(30)
    await openVisibleVideo(page)
    await expect(nav(page, '分类')).toHaveAttribute('aria-current', 'page')
    await expect(nav(page, '我')).not.toHaveAttribute('aria-current', 'page')
    await page.goto('/video/1005')
    await expect(page.locator('h2')).toBeVisible()
    await expect(nav(page, '分类')).toHaveAttribute('aria-current', 'page')
    await expect(page.locator('nav.bottom-nav [aria-current="page"]')).toHaveCount(1)
  })

  test('列表页、详情页点底部「分类」回到 /long，之后进入列表不恢复旧状态', async ({ page }) => {
    await setupLong(page)
    await page.goto('/long/category/1')
    await expect(tiles(page)).toHaveCount(30)
    await nav(page, '分类').click()
    await expect(page).toHaveURL(/\/long$/)
    await homeCards(page).filter({ hasText: '教育' }).click()
    await expect(tiles(page).first()).toContainText('教育视频 3001')
    await scrollListTo(page, 1500)
    await openVisibleVideo(page)
    await nav(page, '分类').click()
    await expect(page).toHaveURL(/\/long$/)
    await homeCards(page).filter({ hasText: '教育' }).click()
    await expect(tiles(page).first()).toContainText('教育视频 3001')
    expect(await scrollTop(page)).toBe(0)
  })

  test('我 → 我的视频 → 详情 → 底部「分类」：清除 videoFrom，之后从列表进详情高亮「分类」', async ({ page }) => {
    await setupLong(page)
    await page.goto('/me')
    await page.getByRole('button', { name: '播放：我的视频 7001' }).click()
    await expect(page).toHaveURL(/\/video\/7001$/)
    await expect(nav(page, '我')).toHaveAttribute('aria-current', 'page')
    expect(await page.evaluate(() => history.state?.videoFrom)).toBe('me')
    await nav(page, '分类').click()
    await expect(page).toHaveURL(/\/long$/)
    await expect(nav(page, '分类')).toHaveAttribute('aria-current', 'page')
    expect(await page.evaluate(() => history.state?.videoFrom), 'cleared by the tab replace').toBeUndefined()
    await homeCards(page).filter({ hasText: '影视剧' }).click()
    await expect(tiles(page)).toHaveCount(30)
    await openVisibleVideo(page)
    expect(await page.evaluate(() => history.state?.videoFrom)).toBeUndefined()
    await expect(nav(page, '分类')).toHaveAttribute('aria-current', 'page')
    await expect(page.locator('nav.bottom-nav [aria-current="page"]')).toHaveCount(1)
    await page.locator('.more-card').first().click()
    await expect(nav(page, '分类')).toHaveAttribute('aria-current', 'page')
    await page.goBack()
    await page.goBack()
    await expect(page).toHaveURL(/\/long\/category\/1$/)
    await page.goBack()
    await expect(page).toHaveURL(/\/long$/)
    expect(await page.evaluate(() => history.state?.videoFrom)).toBeUndefined()
    await expect(nav(page, '分类')).toHaveAttribute('aria-current', 'page')
  })
})
